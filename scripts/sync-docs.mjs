import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import {
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  statSync,
  writeFileSync,
} from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const siteRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const contentRoot = join(siteRoot, 'src/docs/content');
const manifestPath = join(siteRoot, 'docs-sync-manifest.json');
const frameworkAdrIndexPath = join(siteRoot, 'src/docs/framework-adrs.generated.ts');

function argumentValue(name) {
  const index = process.argv.indexOf(name);
  return index >= 0 ? process.argv.at(index + 1) : undefined;
}

function discoverFrameworkRoot() {
  const candidates = [
    process.env.ECHO_AGENT_ROOT,
    resolve(siteRoot, '../echo-agent'),
    resolve(siteRoot, '../../echo-agent'),
  ].filter(Boolean);
  const frameworkRoot = candidates.find(
    (candidate) =>
      existsSync(join(candidate, 'Cargo.toml')) && existsSync(join(candidate, 'docs/en')),
  );

  if (!frameworkRoot) {
    throw new Error(
      'Could not find echo-agent. Set ECHO_AGENT_ROOT or pass --framework-root <path>.',
    );
  }
  return frameworkRoot;
}

function discoverApplicationRoot() {
  const candidates = [
    process.env.ECHO_AGENT_CLI_ROOT,
    resolve(siteRoot, '../echo-agent-cli'),
    resolve(siteRoot, '../../echo-agent-cli'),
  ].filter(Boolean);
  const applicationRoot = candidates.find(
    (candidate) =>
      existsSync(join(candidate, 'Cargo.toml')) &&
      existsSync(join(candidate, 'echo-agent-app-core')),
  );

  if (!applicationRoot) {
    throw new Error(
      'Could not find echo-agent-cli. Set ECHO_AGENT_CLI_ROOT or pass --application-root <path>.',
    );
  }
  return applicationRoot;
}

function filesBelow(directory) {
  if (!existsSync(directory)) return [];
  return readdirSync(directory, { withFileTypes: true })
    .flatMap((entry) => {
      const path = join(directory, entry.name);
      return entry.isDirectory() ? filesBelow(path) : [path];
    })
    .filter((path) => path.endsWith('.md'))
    .sort();
}

function sha256(path) {
  return createHash('sha256').update(readFileSync(path)).digest('hex');
}

function relativeMarkdownPaths(directory) {
  return filesBelow(directory).map((path) => relative(directory, path).replaceAll('\\', '/'));
}

function typescriptString(value) {
  return `'${value
    .replaceAll('\\', '\\\\')
    .replaceAll("'", "\\'")
    .replaceAll('\r', '\\r')
    .replaceAll('\n', '\\n')}'`;
}

function frameworkAdrEntries(sourceRoot, relativePaths) {
  return relativePaths.map((relativePath) => {
    const source = join(sourceRoot, relativePath);
    const title = readFileSync(source, 'utf8')
      .match(/^#\s+(.+)$/m)?.[1]
      ?.trim();
    if (!title) {
      throw new Error(`Framework ADR has no Markdown title: ${relativePath}`);
    }
    const routeName = relativePath
      .replace(/\.md$/, '')
      .replace(/[^a-zA-Z0-9]+/g, '-')
      .replace(/^-|-$/g, '')
      .toLowerCase();
    return {
      slug: `adr-${routeName}`,
      title,
      filePath: `./content/echo-agent/adr/${relativePath}`,
    };
  });
}

function renderFrameworkAdrIndex(entries) {
  const lines = [
    '// Generated by scripts/sync-docs.mjs. Do not edit by hand.',
    '',
    'export const frameworkAdrDocs = [',
  ];
  for (const entry of entries) {
    lines.push(
      '  {',
      `    slug: ${typescriptString(entry.slug)},`,
      '    title: {',
      `      zh: ${typescriptString(entry.title)},`,
      `      en: ${typescriptString(entry.title)},`,
      '    },',
      `    filePath: ${typescriptString(entry.filePath)},`,
      '  },',
    );
  }
  lines.push('];', '');
  return lines.join('\n');
}

function verifyFrameworkAdrIndex(manifest) {
  const adrRecords = manifest.framework.files.filter((record) =>
    record.sourcePath.startsWith('docs/adr/'),
  );
  const englishRecords = adrRecords.filter((record) =>
    record.destination.startsWith('src/docs/content/echo-agent/en/adr/'),
  );
  if (englishRecords.length === 0 || adrRecords.length !== englishRecords.length * 2) {
    throw new Error('Framework ADR manifest must publish every ADR in both languages.');
  }
  const destinations = new Set(adrRecords.map((record) => record.destination));
  for (const record of englishRecords) {
    const relativePath = record.sourcePath.slice('docs/adr/'.length);
    for (const language of ['en', 'zh']) {
      const destination = `src/docs/content/echo-agent/${language}/adr/${relativePath}`;
      if (!destinations.has(destination)) {
        throw new Error(`Framework ADR manifest is missing: ${destination}`);
      }
    }
  }
  const expected = renderFrameworkAdrIndex(
    frameworkAdrEntries(
      join(contentRoot, 'echo-agent/en/adr'),
      englishRecords.map((record) => record.sourcePath.slice('docs/adr/'.length)).sort(),
    ),
  );
  if (
    !existsSync(frameworkAdrIndexPath) ||
    readFileSync(frameworkAdrIndexPath, 'utf8') !== expected
  ) {
    throw new Error('Framework ADR registry drifted; run the documentation synchronization.');
  }
}

function copyTree(destinationRoot, sourcePrefix, relativePaths, documents) {
  return relativePaths.map((relativePath) => {
    const sourcePath = `${sourcePrefix}/${relativePath}`;
    const destination = join(destinationRoot, relativePath);
    mkdirSync(dirname(destination), { recursive: true });
    writeFileSync(destination, documents.get(sourcePath));
    return {
      sourcePath,
      destination: relative(siteRoot, destination).replaceAll('\\', '/'),
      sha256: sha256(destination),
    };
  });
}

function gitRevision(repositoryRoot) {
  return execFileSync('git', ['rev-parse', 'HEAD'], {
    cwd: repositoryRoot,
    encoding: 'utf8',
  }).trim();
}

function assertCleanSource(repositoryRoot, label) {
  const resolvedRoot = resolve(repositoryRoot);
  const status = execFileSync('git', ['status', '--porcelain=v1', '--untracked-files=all'], {
    cwd: resolvedRoot,
    encoding: 'utf8',
  }).trim();
  if (status) {
    throw new Error(
      `${label} source is dirty; refusing to sync files under a clean HEAD revision:\n${status}`,
    );
  }
}

function frameworkSnapshot(repositoryRoot) {
  const root = resolve(repositoryRoot);
  assertCleanSource(root, 'echo-agent');
  const revision = gitRevision(root);
  const tree = execFileSync(
    'git',
    [
      'ls-tree',
      '-rz',
      revision,
      '--',
      'docs/en',
      'docs/zh',
      'docs/adr',
      'docs/internal/knowledge/en',
      'docs/internal/knowledge/zh',
    ],
    { cwd: root, encoding: 'utf8' },
  );
  const tracked = new Map();
  for (const entry of tree.split('\0').filter(Boolean)) {
    const separator = entry.indexOf('\t');
    const sourcePath = entry.slice(separator + 1);
    if (!sourcePath.endsWith('.md')) continue;
    const [mode, kind, blob] = entry.slice(0, separator).split(' ');
    if (kind !== 'blob' || !['100644', '100755'].includes(mode)) {
      throw new Error(`Framework documentation is not a regular Git file: ${sourcePath}`);
    }
    tracked.set(sourcePath, blob);
  }
  const pathsBelow = (prefix) =>
    [...tracked.keys()]
      .filter((path) => path.startsWith(`${prefix}/`))
      .map((path) => path.slice(prefix.length + 1))
      .sort();
  const pairedPaths = (english, chinese) =>
    pathsBelow(english).filter((path) => tracked.has(`${chinese}/${path}`));
  const standardPaths = pairedPaths('docs/en', 'docs/zh');
  const knowledgePaths = pairedPaths('docs/internal/knowledge/en', 'docs/internal/knowledge/zh');
  const adrPaths = pathsBelow('docs/adr');
  if (adrPaths.length === 0) {
    throw new Error('Framework documentation contains no ADR files.');
  }
  // 当前API用法由上游真实示例编译和文档审查确认；这里仅证明固定Git来源与逐字节镜像。
  // 不从Rust fence、注释、字符串或迁移说明中的名称推断可执行性，以免阻断合法源同步。
  // 历史ADR、旧版对照及自定义工具均保持来源原文，后继内容只能随合格上游快照更新。
  const documents = new Map();
  const files = [];
  for (const language of ['en', 'zh']) {
    for (const [sourcePrefix, paths, destinationPrefix] of [
      [`docs/${language}`, standardPaths, `src/docs/content/echo-agent/${language}`],
      [
        `docs/internal/knowledge/${language}`,
        knowledgePaths,
        `src/docs/content/echo-agent/${language}/knowledge`,
      ],
      ['docs/adr', adrPaths, `src/docs/content/echo-agent/${language}/adr`],
    ]) {
      for (const path of paths) {
        const sourcePath = `${sourcePrefix}/${path}`;
        if (!documents.has(sourcePath)) {
          const content = execFileSync('git', ['cat-file', 'blob', tracked.get(sourcePath)], {
            cwd: root,
            maxBuffer: 16 * 1024 * 1024,
          });
          if (!readFileSync(join(root, sourcePath)).equals(content)) {
            throw new Error(`Framework documentation differs from HEAD blob: ${sourcePath}`);
          }
          documents.set(sourcePath, content);
        }
        files.push({
          sourcePath,
          destination: `${destinationPrefix}/${path}`,
          sha256: createHash('sha256').update(documents.get(sourcePath)).digest('hex'),
        });
      }
    }
  }
  // 固定同一个 Git 修订和受控集合，不能把忽略文件或途中切换的 HEAD 冒作该来源。
  if (gitRevision(root) !== revision) {
    throw new Error('Framework HEAD changed while reading the documentation snapshot.');
  }
  return {
    revision,
    standardPaths,
    knowledgePaths,
    adrPaths,
    documents,
    files: files.sort((left, right) => left.destination.localeCompare(right.destination)),
  };
}

function assertApplicationParity(applicationRoot) {
  execFileSync('node', ['scripts/check-docs-parity.mjs'], {
    cwd: resolve(applicationRoot),
    encoding: 'utf8',
    stdio: 'pipe',
  });
}

function applicationSourceFiles(applicationRoot) {
  const sourceRoot = resolve(applicationRoot);
  const records = [];
  for (const language of ['zh', 'en']) {
    const languageRoot = join(sourceRoot, 'docs', language);
    for (const relativePath of relativeMarkdownPaths(languageRoot)) {
      const source = join(languageRoot, relativePath);
      records.push({
        sourcePath: `docs/${language}/${relativePath}`,
        sha256: sha256(source),
      });
    }
  }
  return records.sort((left, right) => left.sourcePath.localeCompare(right.sourcePath));
}

function projectionFiles() {
  return filesBelow(join(contentRoot, 'eko')).map((path) => ({
    destination: relative(siteRoot, path).replaceAll('\\', '/'),
    sha256: sha256(path),
  }));
}

function applicationProjection(
  applicationRoot,
  applicationRevision,
  applicationStatus,
  applicationAuthority,
  refreshApplicationProjection,
) {
  const existingManifest = existsSync(manifestPath)
    ? JSON.parse(readFileSync(manifestPath, 'utf8'))
    : undefined;
  const existingProjection = existingManifest?.applicationProjection;
  // 未明确审查新产品修订时，整个既有投影（含 sourceFiles）都是原审查身份的一部分。
  if (refreshApplicationProjection) {
    if (!existingProjection?.reviewedRevision) {
      throw new Error('Projection corrections require an existing reviewed application identity.');
    }
    // 页面纠正不是重新审查：旧来源身份原样保留，只生成当前站点正文摘要并明确待复审。
    return {
      ...existingProjection,
      status: 'source-correction-pending-source-review',
      files: projectionFiles(),
    };
  }
  if (!applicationRevision && existingProjection) return existingProjection;
  const reviewedRevision = applicationRevision ?? existingProjection?.reviewedRevision;
  if (!reviewedRevision) {
    throw new Error(
      'Pass --application-revision <sha> for the initial documentation synchronization.',
    );
  }

  return {
    repository: existingProjection?.repository ?? 'https://github.com/EchoYue-lp/echo-agent-cli',
    reviewedRevision,
    status: applicationStatus ?? existingProjection?.status ?? 'pending-application-review-sync',
    authority:
      applicationAuthority ??
      existingProjection?.authority ??
      'Website pages are reviewed product projections. The complete bilingual EKO source tree remains authoritative in echo-agent-cli/docs/{zh,en}.',
    sourceFiles: applicationSourceFiles(applicationRoot),
    files: projectionFiles(),
  };
}

function syncFramework(
  frameworkRoot,
  applicationRoot,
  applicationRevision,
  applicationStatus,
  applicationAuthority,
  refreshApplicationProjection,
) {
  const resolvedRoot = resolve(frameworkRoot);
  for (const required of [
    'docs/en',
    'docs/zh',
    'docs/adr',
    'docs/internal/knowledge/en',
    'docs/internal/knowledge/zh',
  ]) {
    if (!statSync(join(resolvedRoot, required)).isDirectory()) {
      throw new Error(`Framework documentation directory is missing: ${required}`);
    }
  }

  const snapshot = frameworkSnapshot(resolvedRoot);
  const projection = applicationProjection(
    applicationRoot,
    applicationRevision,
    applicationStatus,
    applicationAuthority,
    refreshApplicationProjection,
  );
  const destinationRoot = join(contentRoot, 'echo-agent');
  rmSync(destinationRoot, { recursive: true, force: true });
  rmSync(join(contentRoot, 'echo-agent-cli'), { recursive: true, force: true });

  const { standardPaths, knowledgePaths, adrPaths, documents } = snapshot;
  const files = [];
  for (const language of ['en', 'zh']) {
    files.push(
      ...copyTree(join(destinationRoot, language), `docs/${language}`, standardPaths, documents),
      ...copyTree(
        join(destinationRoot, language, 'knowledge'),
        `docs/internal/knowledge/${language}`,
        knowledgePaths,
        documents,
      ),
      ...copyTree(join(destinationRoot, language, 'adr'), 'docs/adr', adrPaths, documents),
    );
  }
  writeFileSync(
    frameworkAdrIndexPath,
    renderFrameworkAdrIndex(frameworkAdrEntries(join(destinationRoot, 'en/adr'), adrPaths)),
  );

  const manifest = {
    schemaVersion: 1,
    framework: {
      repository: 'https://github.com/EchoYue-lp/echo-agent',
      revision: snapshot.revision,
      authority:
        'Framework documents with matching English and Chinese source paths are copied without semantic edits. Language-specific contributor material remains authoritative upstream.',
      files: files.sort((left, right) => left.destination.localeCompare(right.destination)),
    },
    applicationProjection: projection,
  };

  writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);
}

function verifyRecord(record) {
  const path = join(siteRoot, record.destination);
  if (!existsSync(path))
    throw new Error(`Vendored documentation is missing: ${record.destination}`);
  if (sha256(path) !== record.sha256) {
    throw new Error(
      `Vendored documentation changed without a manifest update: ${record.destination}`,
    );
  }
}

function checkManifest(
  frameworkRoot,
  applicationRoot,
  manifest = JSON.parse(readFileSync(manifestPath, 'utf8')),
) {
  const records = [...manifest.framework.files, ...manifest.applicationProjection.files];
  records.forEach(verifyRecord);
  verifyFrameworkAdrIndex(manifest);

  const tracked = new Set(records.map((record) => record.destination));
  const present = filesBelow(contentRoot).map((path) =>
    relative(siteRoot, path).replaceAll('\\', '/'),
  );
  const unexpected = present.filter((path) => !tracked.has(path));
  if (unexpected.length > 0) {
    throw new Error(
      `Documentation files are not tracked by the sync manifest:\n${unexpected.join('\n')}`,
    );
  }

  if (frameworkRoot) {
    const resolvedRoot = resolve(frameworkRoot);
    const snapshot = frameworkSnapshot(resolvedRoot);
    const currentRevision = snapshot.revision;
    if (currentRevision !== manifest.framework.revision) {
      throw new Error(
        `Framework docs need synchronization: manifest=${manifest.framework.revision}, source=${currentRevision}`,
      );
    }
    const expected = new Map(snapshot.files.map((record) => [record.destination, record]));
    const destinations = new Set();
    for (const record of manifest.framework.files) {
      const sourceRecord = expected.get(record.destination);
      if (
        destinations.has(record.destination) ||
        !sourceRecord ||
        sourceRecord.sourcePath !== record.sourcePath ||
        sourceRecord.sha256 !== record.sha256
      ) {
        throw new Error(
          `Framework documentation is outside the source snapshot: ${record.sourcePath}`,
        );
      }
      destinations.add(record.destination);
    }
    if (destinations.size !== expected.size) {
      throw new Error(
        'Framework manifest omits controlled documentation from the source snapshot.',
      );
    }
  }

  if (applicationRoot) {
    const resolvedRoot = resolve(applicationRoot);
    assertApplicationParity(resolvedRoot);
    for (const record of manifest.applicationProjection.sourceFiles ?? []) {
      const source = join(resolvedRoot, record.sourcePath);
      if (!existsSync(source) || sha256(source) !== record.sha256) {
        throw new Error(`EKO bilingual source docs drifted: ${record.sourcePath}`);
      }
    }
    const currentRevision = gitRevision(resolvedRoot);
    if (currentRevision !== manifest.applicationProjection.reviewedRevision) {
      throw new Error(
        `EKO projections need review: manifest=${manifest.applicationProjection.reviewedRevision}, source=${currentRevision}`,
      );
    }
  }

  for (const path of filesBelow(join(contentRoot, 'eko'))) {
    const content = readFileSync(path, 'utf8');
    for (const staleClaim of ['EchoCoWork', '10-100', '67+']) {
      if (content.includes(staleClaim)) {
        throw new Error(`Stale product claim found in ${relative(siteRoot, path)}: ${staleClaim}`);
      }
    }
  }
}

const frameworkRootArgument = argumentValue('--framework-root');
const applicationRootArgument = argumentValue('--application-root');
const applicationRevision = argumentValue('--application-revision');
const applicationStatus = argumentValue('--application-status');
const applicationAuthority = argumentValue('--application-authority');
const refreshApplicationProjection = process.argv.includes('--refresh-application-projection');
if (
  refreshApplicationProjection &&
  ['--check', '--application-revision', '--application-status', '--application-authority'].some(
    (option) => process.argv.includes(option),
  )
) {
  throw new Error(
    'Projection corrections cannot be combined with check or application review metadata changes.',
  );
}
const frameworkRoot =
  frameworkRootArgument === 'auto' ? discoverFrameworkRoot() : frameworkRootArgument;
const applicationRoot =
  applicationRootArgument === 'auto' ? discoverApplicationRoot() : applicationRootArgument;
if (process.argv.includes('--check')) {
  checkManifest(frameworkRoot, applicationRoot);
} else if (refreshApplicationProjection && !frameworkRoot) {
  // 产品页面纠正不要求重新审阅框架；原框架正文和来源身份必须先校验并原样保留。
  // 显式提供 framework-root 时仍走原完整同步，不绕过其 clean-source 检查。
  const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));
  const projection = applicationProjection(undefined, undefined, undefined, undefined, true);
  const candidate = { ...manifest, applicationProjection: projection };
  // 同一完整校验先检查候选；错误页面或未登记文件不能在命令失败后留下新摘要。
  checkManifest(undefined, undefined, candidate);
  writeFileSync(manifestPath, `${JSON.stringify(candidate, null, 2)}\n`);
} else {
  if (!frameworkRoot) throw new Error('Pass --framework-root <path> when synchronizing docs.');
  let requiredApplicationRoot;
  if ((applicationStatus || applicationAuthority) && !applicationRevision) {
    throw new Error(
      'Changing application projection status or authority requires --application-revision <reviewed-sha>.',
    );
  }
  if (applicationRevision) {
    requiredApplicationRoot = applicationRoot ?? discoverApplicationRoot();
    assertCleanSource(requiredApplicationRoot, 'echo-agent-cli');
    assertApplicationParity(requiredApplicationRoot);
    const currentApplicationRevision = gitRevision(resolve(requiredApplicationRoot));
    if (applicationRevision !== currentApplicationRevision) {
      throw new Error(
        `Application revision does not match the clean source: requested=${applicationRevision}, source=${currentApplicationRevision}`,
      );
    }
  }
  syncFramework(
    frameworkRoot,
    requiredApplicationRoot,
    applicationRevision,
    applicationStatus,
    applicationAuthority,
    refreshApplicationProjection,
  );
  checkManifest(frameworkRoot, applicationRevision ? requiredApplicationRoot : undefined);
}
